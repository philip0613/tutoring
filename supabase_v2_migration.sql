-- 1. profiles 테이블 role 기본값 및 확장 점검
-- (선생님 role: 'admin' 또는 'teacher', 학생: 'student')
DO $$
BEGIN
    -- profiles 테이블이 존재하는지 확인하고 필요시 컬럼 추가
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name='profiles' AND column_name='created_at'
    ) THEN
        ALTER TABLE profiles ADD COLUMN created_at timestamp with time zone DEFAULT timezone('utc'::text, now());
    END IF;
END $$;


-- 2. 과목 관리 테이블 (subjects)
-- 선생님이 개설하는 과목 단위 (예: 고1 수학, 중3 영어 등)
CREATE TABLE IF NOT EXISTS subjects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id uuid REFERENCES profiles(id) ON DELETE CASCADE NOT NULL,
    name text NOT NULL,
    description text,
    color text DEFAULT '#4F46E5', -- UI 캘린더 및 뱃지용 대표 색상
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 3. 학생-과목 수강 연결 테이블 (enrollments)
-- 한 과목에 여러 학생이 등록되고, 한 학생이 여러 과목을 수강할 수 있는 다대다(N:M) 구조
CREATE TABLE IF NOT EXISTS enrollments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id bigint REFERENCES subjects(id) ON DELETE CASCADE NOT NULL,
    student_id uuid REFERENCES profiles(id) ON DELETE CASCADE NOT NULL,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_subject_student UNIQUE (subject_id, student_id)
);


-- 4. 수업 캘린더 및 일정 테이블 (schedules)
-- 과목별 수업 일정, 시간, 출결 및 수업 메모 관리
CREATE TABLE IF NOT EXISTS schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id bigint REFERENCES subjects(id) ON DELETE CASCADE NOT NULL,
    teacher_id uuid REFERENCES profiles(id) ON DELETE CASCADE NOT NULL,
    student_id uuid REFERENCES profiles(id) ON DELETE CASCADE, -- 특정 학생 1:1 수업일 경우 설정, 비어있으면 과목 전체 공통
    title text NOT NULL,
    start_time timestamp with time zone NOT NULL,
    end_time timestamp with time zone NOT NULL,
    status text DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'completed', 'cancelled', 'makeup')),
    notes text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 5. 웹 푸시 알림 구독 테이블 (push_subscriptions)
-- 기기별 Web Push 구독 정보 (브라우저 Push Manager)
CREATE TABLE IF NOT EXISTS push_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES profiles(id) ON DELETE CASCADE NOT NULL,
    endpoint text NOT NULL UNIQUE,
    p256dh text NOT NULL,
    auth text NOT NULL,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 6. 인앱 알림 내역 테이블 (notifications)
-- 푸시 수신 외에도 웹 내에서 최근 알림 내역을 볼 수 있도록 지원
CREATE TABLE IF NOT EXISTS notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES profiles(id) ON DELETE CASCADE NOT NULL,
    title text NOT NULL,
    body text NOT NULL,
    link text,
    is_read boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 7. 기존 v1 테이블에 subject_id 컬럼 안전하게 추가 (과목 단위 연결)
DO $$
BEGIN
    -- questions 테이블에 subject_id 추가
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name='questions' AND column_name='subject_id'
    ) THEN
        ALTER TABLE questions ADD COLUMN subject_id bigint REFERENCES subjects(id) ON DELETE SET NULL;
    END IF;

    -- exams 테이블에 subject_id 추가
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name='exams' AND column_name='subject_id'
    ) THEN
        ALTER TABLE exams ADD COLUMN subject_id bigint REFERENCES subjects(id) ON DELETE SET NULL;
    END IF;

    -- feedbacks 테이블에 subject_id 추가
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_name='feedbacks' AND column_name='subject_id'
    ) THEN
        ALTER TABLE feedbacks ADD COLUMN subject_id bigint REFERENCES subjects(id) ON DELETE SET NULL;
    END IF;
END $$;


-- 8. 성능 최적화를 위한 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_subjects_teacher ON subjects(teacher_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_subject ON enrollments(subject_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_student ON enrollments(student_id);
CREATE INDEX IF NOT EXISTS idx_schedules_subject ON schedules(subject_id);
CREATE INDEX IF NOT EXISTS idx_schedules_start ON schedules(start_time);
CREATE INDEX IF NOT EXISTS idx_questions_subject ON questions(subject_id);
CREATE INDEX IF NOT EXISTS idx_exams_subject ON exams(subject_id);
CREATE INDEX IF NOT EXISTS idx_feedbacks_subject ON feedbacks(subject_id);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id);


-- 9. 보안망(RLS) 비활성화 유지 (Vercel Serverless 백엔드 API에서 검증 처리)
ALTER TABLE IF EXISTS subjects DISABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS enrollments DISABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS schedules DISABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS push_subscriptions DISABLE ROW LEVEL SECURITY;
ALTER TABLE IF EXISTS notifications DISABLE ROW LEVEL SECURITY;
